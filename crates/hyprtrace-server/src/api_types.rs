//! The TypeScript bindings for the API models, generated from the Rust ones.
//!
//! `web/src/lib/api-types.ts` is a **build artifact that is committed**: this
//! module renders it, and `api_types_are_in_sync` fails when the committed file
//! differs from what the models produce. The frontend imports its types from
//! there, so the contract cannot drift from the server the way a hand-written
//! copy does — the failure mode this exists to prevent is a field being renamed
//! in Rust and the SPA reading `undefined` at runtime, with every type check
//! still green.
//!
//! The module is compiled for tests only: rendering bindings is a build-time
//! concern, and shipping the renderer in the binary would leave two `pub` items
//! that nothing but a test reads (which is a dead-code warning, as this
//! repository has now learned four times).
//!
//! To regenerate after changing a model:
//!
//! ```text
//! HYPRTRACE_WRITE_TYPES=1 cargo test -p hyprtrace-server api_types
//! ```

use crate::models::{
    ActivityEvent, AiMessage, AppMetadata, AppRank, AppResource, CategoryRule, CurrentStatus,
    DailyActivity, DailyTrend, DisruptionEvent, EfficiencyScore, Goal, GoalProgress, HourlyBucket,
    Project, ProjectRule, ProjectStat, SearchHit, Session, TitleStat, TodaySummary,
    TrendPrediction, WorkspaceRecommendation,
};
use ts_rs::{Config, TS};

/// ts-rs renders a type as if it were its own file: it announces itself with a
/// header and imports the types it references from `"./Name"`. We bundle
/// everything into one file, so both are wrong there — the import would point at
/// a module that does not exist, and the header would be repeated per type.
///
/// Dropping them is safe because the imports are only needed across files and
/// every type they name is rendered into the same bundle; if ts-rs ever changed
/// the shape of what it emits, the leftover would be a dangling import, which
/// `tsc` rejects rather than ignores.
fn strip_per_file_artifacts(rendered: &str) -> String {
    rendered
        .lines()
        .filter(|line| {
            !line.starts_with("// This file was generated by")
                && !line.starts_with("import type ")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Every type `/api` hands to the frontend, in the order they appear in the file.
///
/// `PaginatedResponse<T>` is deliberately absent: it is generic, and the two
/// instantiations the API actually returns (`Session`, `AiMessage`) are declared
/// by hand in `web/src/lib/types.ts` where the frontend can name them.
macro_rules! render_types {
    ($cfg:expr, $($ty:ty),* $(,)?) => {{
        let mut out = String::new();
        $(
            let rendered = <$ty>::export_to_string($cfg)
                .expect("ts-rs must be able to render every API model");
            out.push_str(&strip_per_file_artifacts(&rendered));
            out.push('\n');
        )*
        out
    }};
}

/// The whole generated file, as a string.
pub fn render() -> String {
    // 64-bit integers must stay `number`. ts-rs defaults to `bigint`, which
    // would be wrong twice over: JSON has no bigint, so the values would never
    // arrive as one, and the frontend does arithmetic on every duration and
    // millisecond field.
    let cfg = Config::new().with_large_int("number");

    let body = render_types!(
        &cfg,
        AppMetadata,
        TodaySummary,
        AppRank,
        CategoryRule,
        HourlyBucket,
        Session,
        SearchHit,
        DailyTrend,
        DailyActivity,
        TitleStat,
        AiMessage,
        AppResource,
        ActivityEvent,
        DisruptionEvent,
        EfficiencyScore,
        Goal,
        GoalProgress,
        TrendPrediction,
        CurrentStatus,
        WorkspaceRecommendation,
        Project,
        ProjectRule,
        ProjectStat,
    );

    format!(
        "// GENERATED FILE — DO NOT EDIT.\n\
         //\n\
         // Rendered from the Rust models by `crates/hyprtrace-server/src/api_types.rs`.\n\
         // Regenerate with:\n\
         //     HYPRTRACE_WRITE_TYPES=1 cargo test -p hyprtrace-server api_types\n\
         // A test fails when this file and the models disagree, so editing it by hand\n\
         // only moves the failure to CI.\n\n\
         {body}"
    )
}

/// Where the generated file lives, resolved from this crate's manifest so the
/// test does not depend on the working directory it is run from.
pub const OUTPUT_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../web/src/lib/api-types.ts"
);

#[cfg(test)]
mod tests {
    use super::*;

    /// The committed artifact is read at run time rather than with
    /// `include_str!`: on the very first run the file does not exist yet, and a
    /// compile-time read would make the generator unable to create it.

    #[test]
    fn api_types_are_in_sync_with_the_models() {
        let generated = render();

        // Regeneration mode: the same test writes the file instead of failing,
        // so updating the bindings is one command rather than a copy-paste out
        // of an assertion diff.
        if std::env::var("HYPRTRACE_WRITE_TYPES").is_ok() {
            std::fs::write(OUTPUT_PATH, &generated).expect("writing the generated bindings");
            eprintln!("wrote {OUTPUT_PATH}");
            return;
        }

        let committed = std::fs::read_to_string(OUTPUT_PATH).unwrap_or_else(|e| {
            panic!(
                "cannot read {OUTPUT_PATH}: {e}\n                 Regenerate the bindings with: HYPRTRACE_WRITE_TYPES=1 cargo test -p hyprtrace-server api_types"
            )
        });

        assert_eq!(
            generated.trim_end(),
            committed.trim_end(),
            "web/src/lib/api-types.ts is out of date with the Rust models. \
             Regenerate it with: HYPRTRACE_WRITE_TYPES=1 cargo test -p hyprtrace-server api_types"
        );
    }

    #[test]
    fn the_bindings_use_numbers_for_milliseconds() {
        let generated = render();
        assert!(
            !generated.contains("bigint"),
            "a 64-bit field became `bigint`; the frontend does arithmetic on these \
             and JSON cannot deliver a bigint"
        );
        assert!(
            generated.contains("total_ms: number"),
            "the duration fields must be plain numbers"
        );
    }
}
